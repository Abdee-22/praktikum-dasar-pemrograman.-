def buat_biodata(nama, umur, jurusan):
    print(f"nama: {nama}")
    print(f"umur: {umur}")
    print(f"jurusan: {jurusan}")
    print("#" * 100)

   #positional argument
buat_biodata("Abdeeeeeeeeeeee", 18, "sistem informasi")

    #keyword Argument
buat_biodata(umur= 19, nama="abdeeeeeeeeeee", jurusan="Sistem Informasi")
